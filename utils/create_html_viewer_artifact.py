
import os
import glob

def create_viewer():
    # Use the artifact directory directly
    root_dir = "/home6/afahad/.gemini/antigravity/brain/046ba57b-b384-4ea0-8903-5a7f2711b141"
    output_html = os.path.join(root_dir, "plots_viewer.html")
    
    # List all PNG files
    png_files = sorted(glob.glob(os.path.join(root_dir, "*.png")))
    
    if not png_files:
        print("No PNG files found!")
        return

    # Extract filenames relative to root_dir
    images = [os.path.basename(f) for f in png_files]
    
    html_content = f"""
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>GF Experiment Comparison Plots</title>
    <style>
        body {{
            font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
            margin: 0;
            padding: 20px;
            text-align: center;
            background-color: #f4f4f9;
        }}
        h1 {{
            color: #333;
            margin-bottom: 30px;
        }}
        .container {{
            max-width: 1200px;
            margin: 0 auto;
            background: white;
            padding: 20px;
            border-radius: 8px;
            box-shadow: 0 4px 6px rgba(0,0,0,0.1);
        }}
        select {{
            padding: 12px;
            font-size: 16px;
            width: 50%;
            max-width: 400px;
            margin-bottom: 20px;
            border-radius: 5px;
            border: 1px solid #ccc;
            cursor: pointer;
        }}
        #plot-container {{
            margin-top: 20px;
            min-height: 500px; /* Prevent layout shift */
            display: flex;
            justify-content: center;
            align-items: center;
        }}
        img {{
            max-width: 100%;
            height: auto;
            border-radius: 4px;
            border: 1px solid #eee;
        }}
        .footer {{
            margin-top: 40px;
            color: #777;
            font-size: 14px;
        }}
    </style>
</head>
<body>

    <div class="container">
        <h1>GF Experiment Comparisons</h1>
        
        <label for="plot-select"><strong>Select Plot:</strong></label><br>
        <select id="plot-select" onchange="updatePlot()">
            {chr(10).join([f'<option value="{img}">{img}</option>' for img in images])}
        </select>
        
        <div id="plot-container">
            <img id="current-plot" src="{images[0]}" alt="Selected Plot">
        </div>
    </div>

    <div class="footer">
        Generated by Antigravity
    </div>

    <script>
        function updatePlot() {{
            var selector = document.getElementById('plot-select');
            var image = document.getElementById('current-plot');
            image.src = selector.value;
        }}
    </script>

</body>
</html>
    """
    
    with open(output_html, 'w') as f:
        f.write(html_content)
        
    print(f"Created HTML viewer: {output_html}")
    print(f"Found {len(images)} images.")

if __name__ == "__main__":
    create_viewer()
