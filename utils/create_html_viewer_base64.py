
import os
import glob
import base64

def create_base64_viewer():
    root_dir = "/home6/afahad/nobackup27/GFEXPv11.7/GFO"
    output_html = os.path.join(root_dir, "plots_viewer_standalone.html")
    
    # List all PNG files
    png_files = sorted(glob.glob(os.path.join(root_dir, "*.png")))
    
    if not png_files:
        print("No PNG files found!")
        return

    print(f"Found {len(png_files)} images. Encoding to Base64 (this may take a moment)...")
    
    # Create list of (filename, base64_string)
    images_data = []
    for fpath in png_files:
        fname = os.path.basename(fpath)
        with open(fpath, "rb") as image_file:
            encoded_string = base64.b64encode(image_file.read()).decode('utf-8')
            images_data.append((fname, f"data:image/png;base64,{encoded_string}"))
        print(f"  Encoded {fname}")
    
    html_content = f"""
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>GF Experiment Comparison Plots (Standalone)</title>
    <style>
        body {{
            font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
            margin: 0;
            padding: 20px;
            text-align: center;
            background-color: #f4f4f9;
        }}
        h1 {{
            color: #333;
            margin-bottom: 20px;
        }}
        p {{
            color: #555;
            margin-bottom: 30px;
        }}
        .container {{
            max-width: 1200px;
            margin: 0 auto;
            background: white;
            padding: 20px;
            border-radius: 8px;
            box-shadow: 0 4px 6px rgba(0,0,0,0.1);
        }}
        select {{
            padding: 12px;
            font-size: 16px;
            width: 50%;
            max-width: 400px;
            margin-bottom: 20px;
            border-radius: 5px;
            border: 1px solid #ccc;
            cursor: pointer;
        }}
        #plot-container {{
            margin-top: 20px;
            min-height: 500px;
            display: flex;
            justify-content: center;
            align-items: center;
        }}
        img {{
            max-width: 100%;
            height: auto;
            border-radius: 4px;
            border: 1px solid #eee;
        }}
        .footer {{
            margin-top: 40px;
            color: #777;
            font-size: 12px;
        }}
    </style>
</head>
<body>

    <div class="container">
        <h1>GF Experiment Comparisons</h1>
        <p>This is a standalone file. All images are embedded.</p>
        
        <label for="plot-select"><strong>Select Plot:</strong></label><br>
        <select id="plot-select" onchange="updatePlot()">
            {chr(10).join([f'<option value="{i}">{name}</option>' for i, (name, _) in enumerate(images_data)])}
        </select>
        
        <div id="plot-container">
            <img id="current-plot" src="{images_data[0][1]}" alt="Selected Plot">
        </div>
    </div>

    <div class="footer">
        Generated by Antigravity (Standalone Version)
    </div>

    <script>
        // Array of base64 images
        const images = [
            {','.join([f'"{b64}"' for _, b64 in images_data])}
        ];

        function updatePlot() {{
            var selector = document.getElementById('plot-select');
            var image = document.getElementById('current-plot');
            // selector value is the index
            var index = parseInt(selector.value);
            image.src = images[index];
        }}
    </script>

</body>
</html>
    """
    
    with open(output_html, 'w') as f:
        f.write(html_content)
        
    print(f"Created Standalone HTML viewer: {output_html}")

if __name__ == "__main__":
    create_base64_viewer()
